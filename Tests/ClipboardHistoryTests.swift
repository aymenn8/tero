@Test func clipboardMigratesOldEntriesAndRestrictsLinks() throws {
    let legacy = Data("{\"entries\":[{\"id\":\"00000000-0000-0000-0000-000000000001\",\"text\":\"legacy\",\"copiedAt\":0}]}".utf8)
    let history = try JSONDecoder().decode(ClipboardHistory.self, from: legacy)
    #expect(history.entries.first?.kind == .text)
    #expect(history.entries.first?.sourceName == nil)
    #expect(ClipboardEntry(text: "https://example.com/page", copiedAt: Date()).kind == .link)
    #expect(ClipboardEntry(text: "javascript:alert(1)", copiedAt: Date()).webURL == nil)
    #expect(ClipboardEntry(text: "file:///tmp/test", copiedAt: Date()).webURL == nil)
}

@Test func clipboardMultimediaDeduplicationAndBudget() {
    let now = Date()
    var history = ClipboardHistory()
    var image = ClipboardEntry(text: "", copiedAt: now, contentKind: .image)
    image.imageData = Data([1, 2, 3])
    history.record(image, now: now)
    history.record(image, now: now)
    #expect(history.entries.count == 1 && history.entries[0].copies == 2)
    var files = ClipboardEntry(text: "", copiedAt: now, contentKind: .files)
    files.files = [ClipboardFile(url: URL(fileURLWithPath: "/tmp/sample.wav"), bookmark: nil, name: "sample.wav", size: 12)]
    history.record(files, now: now)
    #expect(history.entries.first?.kind == .files)
    #expect(history.entries.first?.searchableText.contains("sample.wav") == true)
    for value in 0..<8 {
        var large = ClipboardEntry(text: "", copiedAt: now, contentKind: .image)
        large.imageData = Data(repeating: UInt8(value), count: 5_000_000)
        history.record(large, now: now)
    }
    #expect(history.entries.reduce(0) { $0 + $1.storageBytes } <= ClipboardHistory.maximumStorageBytes)
}


@Test func clipboardPinsSurviveExpiryAndRecopyAndProtectCapacity() throws {
    let now = Date()
    var history = ClipboardHistory()
    history.record("Important", now: now)
    let id = history.entries[0].id
    let pinned = history.setPinned(true, id: id, now: now)
    #expect(pinned)
    history.prune(now: now.addingTimeInterval(ClipboardHistory.retention * 2))
    #expect(history.entries.count == 1 && history.entries[0].isPinned)
    history.record("Important", now: now.addingTimeInterval(ClipboardHistory.retention * 2))
    #expect(history.entries[0].isPinned && history.entries[0].id == id && history.entries[0].copies == 2)
    let restored = try JSONDecoder().decode(ClipboardHistory.self, from: JSONEncoder().encode(history))
    #expect(restored.entries[0].isPinned)
    for index in 0..<130 { history.record("new \(index)", now: now.addingTimeInterval(ClipboardHistory.retention * 2)) }
    #expect(history.entries.count == 100 && history.entries[0].id == id)
    let unpinned = history.setPinned(false, id: id, now: now.addingTimeInterval(ClipboardHistory.retention * 4))
    #expect(unpinned)
    #expect(!history.entries.contains { $0.id == id })
}
@Test func clipboardPinLimitAndLegacyDefault() throws {
    let now = Date(); var history = ClipboardHistory()
    for index in 0..<20 { history.record("pin \(index)", now: now); let pinned = history.setPinned(true, id: history.entries.first { $0.text == "pin \(index)" }!.id, now: now); #expect(pinned) }
    history.record("last", now: now)
    let refused = history.setPinned(true, id: history.entries.first { $0.text == "last" }!.id, now: now)
    #expect(!refused)
    let legacy = Data("{\"entries\":[{\"text\":\"old\",\"copiedAt\":0,\"id\":\"00000000-0000-0000-0000-000000000001\"}]}".utf8)
    #expect(try JSONDecoder().decode(ClipboardHistory.self, from: legacy).entries[0].isPinned == false)
}
@Test func clipboardSearchCombinesContentTypeFilenameAndSource() {
    let now = Date()
    var file = ClipboardEntry(text: "", copiedAt: now, contentKind: .files)
    file.sourceName = "WhatsApp"; file.sourceBundleID = "net.whatsapp.WhatsApp"
    file.files = [.init(url: URL(fileURLWithPath: "/tmp/Résumé.pdf"), bookmark: nil, name: "Résumé.pdf", size: 100)]
    #expect(file.matches("resume whatsapp pdf"))
    #expect(file.matches("type:pdf app:whatsapp"))
    #expect(!file.matches("type:image app:whatsapp"))
    #expect(!file.matches("resume mail"))
}
@Test func clipboardLinkCleaningPreservesMeaningAndSignedQueries() {
    func clean(_ text: String) -> String { ClipboardEntry(text: text, copiedAt: .now).cleanedLink!.absoluteString }
    #expect(clean("https://example.com/a?utm_source=x&id=12&path=a%2Fb&fbclid=z#section") == "https://example.com/a?id=12&path=a%2Fb#section")
    #expect(clean("https://example.com/?UTM_MEDIUM=x") == "https://example.com/")
    #expect(clean("https://example.com/?ref=product&search=music") == "https://example.com/?ref=product&search=music")
    #expect(clean("https://example.com/?sig=abc&utm_source=x") == "https://example.com/?sig=abc&utm_source=x")
    #expect(clean("https://example.com/?&utm_source=x") == "https://example.com/?")
}
