@Test func clipboardDeduplicatesBoundsAndExpires() {
    let now = Date()
    var history = ClipboardHistory()
    history.record("A", now: now.addingTimeInterval(-1))
    history.record("B", now: now)
    history.record("A", now: now)
    #expect(history.entries.map(\.text) == ["A", "B"])
    for index in 0..<110 { history.record("text \(index)", now: now) }
    #expect(history.entries.count == 100)
    #expect(history.entries.first?.text == "text 109")
    history.prune(now: now.addingTimeInterval(ClipboardHistory.retention))
    #expect(history.entries.isEmpty)
}

@Test func clipboardRejectsUnsupportedAndConfidentialContents() {
    var history = ClipboardHistory()
    history.record(" \n ")
    history.record(String(repeating: "é", count: 20_000))
    #expect(history.entries.isEmpty)
    for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
        #expect(!ClipboardHistory.accepts(types: [type, "public.utf8-plain-text"], secureInput: false))
    }
    #expect(!ClipboardHistory.accepts(types: ["public.utf8-plain-text"], secureInput: true))
    #expect(ClipboardHistory.accepts(types: ["public.utf8-plain-text"], secureInput: false))
}

