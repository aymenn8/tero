@Test func clipboardInsertionAcceptsEditableSelectionButRejectsReadOnlyAndProtectedFields() {
    let metadata = SelectionMetadata(range: NSRange(location: 2, length: 4),
        controlBounds: nil, selectionBounds: nil, isEditable: true)
    let selected = SelectionReadout(applicationName: "Test", processIdentifier: 1,
        status: .selected("text"), targetID: UUID(), metadata: metadata)
    #expect(selected.canInsertClipboard)
    var readOnly = selected
    readOnly.metadata = SelectionMetadata(range: metadata.range,
        controlBounds: nil, selectionBounds: nil, isEditable: false)
    #expect(!readOnly.canInsertClipboard)
    let protected = SelectionReadout(applicationName: "Test", processIdentifier: 1,
        status: .protectedField, targetID: UUID(), metadata: metadata)
    #expect(!protected.canInsertClipboard)
}
