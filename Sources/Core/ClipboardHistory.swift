import Foundation

struct ClipboardHistory: Codable {
    var entries: [ClipboardEntry] = []
    static let maximumBytes = 32_768
    static let maximumImageBytes = 5_000_000
    static let maximumStorageBytes = 30_000_000
    static let maximumCount = 100
    static let maximumPinnedCount = 20
    static let retention: TimeInterval = 7 * 24 * 3600

    mutating func prune(now: Date = Date()) {
        var seen = Set<String>()
        var bytes = 0
        let candidates = entries.filter { $0.isValid && ($0.isPinned || now.timeIntervalSince($0.copiedAt) < Self.retention) && $0.copiedAt <= now }.sorted { $0.copiedAt > $1.copiedAt }
        let priority = Array(candidates.filter(\.isPinned).prefix(Self.maximumPinnedCount)) + candidates.filter { !$0.isPinned }
        entries = Array(priority.filter {
            guard seen.insert($0.fingerprint).inserted, bytes + $0.storageBytes <= Self.maximumStorageBytes else { return false }
            bytes += $0.storageBytes
            return true
        }.prefix(Self.maximumCount))
    }

    mutating func record(_ text: String, now: Date = Date()) {
        record(ClipboardEntry(text: text, copiedAt: now), now: now)
    }

    mutating func record(_ candidate: ClipboardEntry, now: Date = Date()) {
        guard candidate.isValid else { return }
        var entry = candidate
        let fingerprint = entry.fingerprint
        let previous = entries.first { $0.fingerprint == fingerprint }
        entry.pinned = previous?.pinned
        if let previous { entry.id = previous.id }
        entry.copies = previous.map { ($0.copies ?? 1) + 1 } ?? 1
        entries.removeAll { $0.fingerprint == fingerprint }
        entries.insert(entry, at: 0)
        prune(now: now)
    }

    @discardableResult mutating func setPinned(_ value: Bool, id: UUID, now: Date = Date()) -> Bool {
        guard let index = entries.firstIndex(where: { $0.id == id }),
          !value || entries[index].isPinned || entries.filter(\.isPinned).count < Self.maximumPinnedCount else { return false }
        entries[index].pinned = value
        prune(now: now)
        return true
    }

    static func accepts(types: Set<String>, secureInput: Bool) -> Bool {
        let excluded: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        return !secureInput && types.isDisjoint(with: excluded)
    }
}
